#!/usr/bin/env python3
"""gen_chrome.py - writes apps/*/hud/layouts/chrome.json (edit here, then regenerate):

    python3 tools/gen_chrome.py

The "Chrom" cluster: three round analogue dials with brushed chrome bezels on a near-black face, after a luxury saloon's
instrument cluster. Left: a 0-100 power-reserve gauge (full at idle, falls as you use power) with the oil temperature
under it. Centre: the speedometer, 0-260 km/h (the labels follow the units, see CHROME_SPEED) with the range and the
average speed under it. Right: fuel (E-F, left half) and coolant (C-H, right half), the clock and the gear in a green
box. The hub is a plain chrome cap, no marque. BMW's black gear box (x 1406-1597, y 342-419) clips the right dial's edge.
"""
import json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTS = [os.path.join(ROOT, 'apps', a, 'hud', 'layouts', 'chrome.json') for a in ('cluster_themes', 'yusuf_dash')]
W = []


def add(**k):
    W.append(k)


CELL = {'c_num': 35, 'c_numL': 44, 'c_txt': 36, 'c_small': 27, 'c_gear': 40}


def text(id, x, y, t, font, color='fg', align='center', w=120, **extra):
    h = CELL[font]
    if align == 'left':
        w = min(w, 1920 - x)
    left = x if align == 'left' else x - w / 2 if align == 'center' else x - w
    d = dict(id=id, type='text', z=5, x=round(left), y=round(y - h / 2), w=w, h=h, text=t, font=font, color=color, align=align)
    d.update(extra)
    add(**d)


def at(cx, cy, theta, r):
    a = math.radians(theta)
    return cx + r * math.sin(a), cy - r * math.cos(a)


def dial(id, cx, cy, R, **k):
    add(id=id, type='chromedial', z=1, x=round(cx - R), y=round(cy - R), w=2 * R, h=2 * R, **{'class': 'content'}, **k)


add(id='bg', type='fill', **{'class': 'content'}, z=0, x=0, y=0, w=1920, h=720, color='bg')

# ---------- centre: speedometer 0-260 km/h
SX, SY, SR = 965, 385, 322
S0, SS = -140.0, 280.0
dial('speedo', SX, SY, SR, kind='speed', start=S0, sweep=SS, minor=4, ringW=26, hub=24, redFrom=2)
rin = SR - 26
tr = rin * 0.93
for i in range(14):
    x, y = at(SX, SY, S0 + i * SS / 13, tr * 0.73)
    text('sp%d' % i, x, y, '{{cdial:%d}}' % i, 'c_num', w=80)
text('sp_u', SX, SY + 105, '{{u:speed}}', 'c_txt', 'dim', w=120)
text('sp_r', SX, SY + 185, '{{range}} {{u:dist}}', 'c_txt', 'fg', w=260)
text('sp_a', SX, SY + 225, 'AVG {{avgSpeed}} {{u:speed}}', 'c_txt', 'dim', w=260)

# ---------- left: power reserve 0-100
LX, LY, LR = 195, 440, 195
L0, LS = -140.0, 230.0
dial('reserve', LX, LY, LR, kind='reserve', start=L0, sweep=LS, ticks=5, minor=4, ringW=20, hub=17)
lt = (LR - 20) * 0.93
for i in range(6):
    x, y = at(LX, LY, L0 + i * LS / 5, lt * 0.64)
    text('rs%d' % i, x, y, str(i * 20), 'c_num', w=70)
text('rs_t', LX, LY + 70, 'POWER', 'c_small', 'dim', w=120)
text('rs_o', LX, LY + 115, 'OIL {{oil}}{{u:temp}}', 'c_txt', 'fg', w=190)

# ---------- right: fuel (E-F left) and coolant (C-H right), clock, gear box
RX, RY, RR = 1735, 440, 180
dial('fuelc', RX, RY, RR, kind='twin', start=-150, sweep=100, start2=50, sweep2=100, ticks=4, ticks2=4, minor=2,
     ringW=20, hub=16)
rt = (RR - 20) * 0.93
for lab, th in (('E', -150), ('F', -50), ('C', 50), ('H', 150)):
    x, y = at(RX, RY, th, rt * 0.70)
    text('fl_' + lab, x, y, lab, 'c_txt', 'fg', w=40)
text('fl_t', RX - 40, RY - 22, 'FUEL', 'c_small', 'dim', w=70)
text('cl_t', RX + 40, RY - 22, 'TEMP', 'c_small', 'dim', w=70)
text('cl_time', RX, RY + 50, '{{time}}', 'c_txt', 'fg', w=140)
add(id='gear_box', type='fill', **{'class': 'content'}, z=3, x=RX - 30, y=RY + 90, w=60, h=46, color='green')
text('gear', RX, RY + 113, '{{gear}}', 'c_gear', 'ink', w=60)

doc = {
    'schemaVersion': 2,
    'name': 'Chrom',
    'packWaste': 3,
    'theme': 'chrome',
    'slots': [],
    '_about': 'Chrome cluster, generated by tools/gen_chrome.py (edit that and regenerate): three round analogue dials.',
    'widgets': W,
}
for out in OUTS:
    with open(out, 'w') as f:
        json.dump(doc, f, indent=2)
        f.write('\n')
print('wrote', len(OUTS), 'layouts,', len(W), 'widgets')
