#!/usr/bin/env python3
"""gen_chrome.py - writes apps/*/hud/layouts/chrome.json (edit here, then regenerate):

    python3 tools/gen_chrome.py

The "Chrom" cluster: three round analogue dials with brushed chrome bezels on a near-black face, after a luxury saloon's
instrument cluster. Left: a 0-100 power-reserve gauge (full at idle, falls as you use power) with the oil temperature
under it. Centre: the speedometer, 0-260 km/h (the labels follow the units, see CHROME_SPEED) with the range and the
average speed under it. Right: fuel (E-F, left half) and coolant (C-H, right half), the clock and the gear in a green
box. The hub is a plain chrome cap, no marque. BMW's black gear box (x 1406-1597, y 342-419) clips the right dial's edge.
"""
import json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTS = [os.path.join(ROOT, 'apps', a, 'hud', 'layouts', 'chrome.json') for a in ('cluster_themes', 'yusuf_dash')]
W = []


def add(**k):
    W.append(k)


CELL = {'c_num': 35, 'c_numL': 44, 'c_txt': 36, 'c_small': 27, 'c_gear': 40}


def text(id, x, y, t, font, color='fg', align='center', w=120, **extra):
    h = CELL[font]
    if align == 'left':
        w = min(w, 1920 - x)
    left = x if align == 'left' else x - w / 2 if align == 'center' else x - w
    d = dict(id=id, type='text', z=5, x=round(left), y=round(y - h / 2), w=w, h=h, text=t, font=font, color=color, align=align)
    d.update(extra)
    add(**d)


def at(cx, cy, theta, r):
    a = math.radians(theta)
    return cx + r * math.sin(a), cy - r * math.cos(a)


def dial(id, cx, cy, R, **k):
    add(id=id, type='chromedial', z=1, x=round(cx - R), y=round(cy - R), w=2 * R, h=2 * R, **{'class': 'content'}, **k)


add(id='bg', type='fill', **{'class': 'content'}, z=0, x=0, y=0, w=1920, h=720, color='bg')

# 1:1 after the photo: the three dials 420 / 350 / 350 px wide there (x 1.6 here), cut flat at the bottom, centres on one
# line (the side dials 20 px lower), the speedometer in the middle of the panel.
K = 1.6
SX, SY, SR = 960, 356, 336
dial('speedo', SX, SY, SR, kind='speed', start=-135, sweep=270, minor=4, ringW=19, hub=52, disc=0.42, cut=0.75,
     sign=[0.395, 0.095, 0.095])
for i in range(14):
    x, y = at(SX, SY, -135 + i * 270 / 13, SR * 0.715)
    text('sp%d' % i, x, y, '{{cdial:%d}}' % i, 'c_num', w=80)
text('sp_u', SX, SY - SR * 0.60, '{{u:speed}}', 'c_small', 'fg', w=100)
text('sp_r', SX, SY + SR * 0.55, '{{range}} {{u:dist}}', 'c_txt', 'fg', w=260)
text('sp_a', SX, SY + SR * 0.64, 'AVG {{avgSpeed}} {{u:speed}}', 'c_txt', 'fg', w=260)

# left: 0-100 power reserve (a needle at 100 when idle)
LX, LY, LR = 325, 390, 280
dial('reserve', LX, LY, LR, kind='reserve', start=-110, sweep=200, ticks=5, minor=4, ringW=16, hub=50, disc=0.46, cut=0.75)
for i in range(6):
    x, y = at(LX, LY, -110 + i * 40, LR * 0.62)
    text('rs%d' % i, x, y, str(i * 20), 'c_num', w=70)
text('rs_o', LX, LY + LR * 0.60, 'OIL {{oil}}{{u:temp}}', 'c_txt', 'fg', w=200)

# right: fuel (E-F, left half) and coolant (H-C, right half), gear on top, clock and coolant under the hub
RX, RY, RR = 1603, 390, 280
dial('fuelc', RX, RY, RR, kind='twin', start=-135, sweep=90, start2=45, sweep2=90, ticks=4, ticks2=4, minor=4,
     ringW=16, hub=50, disc=0.46, cut=0.75)
for lab, th in (('E', -133), ('F', -52), ('H', 52), ('C', 137)):
    x, y = at(RX, RY, th, RR * 0.60)
    text('fl_' + lab, x, y, lab, 'c_txt', 'fg', w=40)
add(id='gear_box', type='fill', **{'class': 'content'}, z=3, x=RX - 30, y=round(RY - RR * 0.58 - 21), w=60, h=42, color='green')
text('gear', RX, RY - RR * 0.58, '{{gear}}', 'c_gear', 'ink', w=60)
text('cl_time', RX - 36, RY + RR * 0.53, '{{time}}', 'c_txt', 'fg', w=150)
text('cl_temp', RX - 36, RY + RR * 0.66, '{{coolant}}{{u:temp}}', 'c_txt', 'fg', w=150)

doc = {
    'schemaVersion': 2,
    'name': 'Chrom',
    'packWaste': 3,
    'theme': 'chrome',
    'slots': [],
    '_about': 'Chrome cluster, generated by tools/gen_chrome.py (edit that and regenerate): three round analogue dials.',
    'widgets': W,
}
for out in OUTS:
    with open(out, 'w') as f:
        json.dump(doc, f, indent=2)
        f.write('\n')
print('wrote', len(OUTS), 'layouts,', len(W), 'widgets')
