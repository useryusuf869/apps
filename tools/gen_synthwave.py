#!/usr/bin/env python3
"""gen_synthwave.py - writes apps/cluster_themes/hud/layouts/synthwave.json (edit here, then regenerate):

    python3 tools/gen_synthwave.py

A neon dusk for the 1920x720 cluster, after the one in sl0w.g26's G26 reel: one shader (the "synth" widget) draws the sky, a
striped sun on the horizon, neon-edged mountains and a perspective grid that runs with the speed. On top: a neon rev
bar across the sky with the rpm under it, the speed in cyan on the left, the gear and drive mode in pink on the
right, the clock on the grid, and four readouts (changeable on the Readouts tab). Clear of BMW's black box
(x 1406-1597, y 342-419), its belt light (x 587-626, y 663-700) and the hood.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'apps', 'hud', 'layouts', 'synthwave.json')

W = []


def add(**k):
    W.append(k)


def text(id, x, y, w, h, text, font, color, align='left', z=5, **extra):
    d = dict(id=id, type='text', z=z, x=x, y=y, w=w, h=h, text=text, font=font, color=color, align=align)
    d.update(extra)
    add(**d)


add(id='bg', type='synth', **{'class': 'content'}, z=0, x=0, y=0, w=1920, h=720, horizon=470, sunX=960, sunR=205)

# rev bar across the sky, the rpm under it
add(id='revs', type='shiftbar', **{'class': 'content'}, z=2, x=400, y=112, w=1120, h=30, segments=40)
text('rpm', 700, 156, 300, 36, '{{rpm}}', 'w_val', 'cyan', 'right', glow=True)
text('rpm_label', 1014, 169, 120, 22, 'RPM', 'w_label', 'violet', 'left')

# speed, left
text('speed', 90, 296, 430, 120, '{{speed}}', 'w_speed', 'fg', 'right', glow=True)
text('speed_unit', 534, 394, 150, 22, '{{u:speed}}', 'w_label', 'violet', 'left', spacing=2)

# gear and drive mode, right of BMW's gear box
text('gear', 1640, 262, 250, 96, '{{gear}}', 'w_gear', 'pink', 'center', glow=True, hotWhen='now')
text('mode', 1600, 232, 300, 22, '{{mode}}', 'w_label', 'violet', 'center', spacing=1)

# clock on the grid
text('clock', 760, 574, 400, 36, '{{time}}', 'w_val', 'fg', 'center', glow=True)

# four readouts on the grid, two each side (left of the belt light's x 587-626 stays clear above y 663)
SLOTS = [('1', 'left, bottom', 'oil', 140), ('2', 'left, bottom', 'coolant', 380),
         ('3', 'right, bottom', 'boost', 1290), ('4', 'right, bottom', 'range', 1530)]
for sid, where, default, x in SLOTS:
    text('slot%s_head' % sid, x, 596, 230, 22, '{{slotHead:%s}} {{slotUnit:%s}}' % (sid, sid), 'w_label', 'violet', 'left', spacing=1)
    text('slot%s' % sid, x, 624, 230, 36, '{{slot:%s}}' % sid, 'w_val', 'cyan', 'left', slot=sid, fit=['w_label'])

doc = {
    'schemaVersion': 2,
    'name': 'Synthwave',
    'packWaste': 3,
    'theme': 'synth',
    'slots': [{'id': i, 'where': w, 'default': d} for i, w, d, _ in SLOTS],
    '_about': 'Synthwave cluster, generated by tools/gen_synthwave.py (edit that and regenerate): a neon dusk. One shader draws the sky, a striped sun, neon-edged mountains and a perspective grid that runs with the speed; on top a neon rev bar with the rpm, the speed in cyan, the gear and drive mode in pink, the clock and four readouts. Clear of BMW\'s black box and belt light. No map window. Widget reference: shared/hud.js header.',
    'widgets': W,
}
with open(OUT, 'w') as f:
    json.dump(doc, f, indent=2)
    f.write('\n')
print('wrote', OUT, len(W), 'widgets')
